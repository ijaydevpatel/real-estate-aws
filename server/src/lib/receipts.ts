import PDFDocument from "pdfkit";

export type ReceiptData = {
  paymentId: number;
  amountDue: number;
  amountPaid: number;
  dueDate: Date;
  paymentDate: Date;
  paymentStatus: string;
  propertyName: string;
  propertyAddress: string;
  tenantName: string;
  tenantEmail: string;
};

const money = (n: number) => `$${n.toFixed(2)}`;
const day = (d: Date) => new Date(d).toLocaleDateString("en-NZ");

/** Renders one receipt and resolves with the finished PDF bytes. */
export const buildReceiptPdf = (data: ReceiptData): Promise<Buffer> =>
  new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 50 });
    const chunks: Buffer[] = [];

    doc.on("data", (c: Buffer) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    doc.fontSize(22).text("Rentiful", { continued: false });
    doc.fontSize(10).fillColor("#666").text("Payment receipt");
    doc.moveDown(1.5);

    doc
      .fillColor("#000")
      .fontSize(14)
      .text(`Receipt #${data.paymentId}`, { continued: false });
    doc.moveDown(0.5);

    const row = (label: string, value: string) => {
      doc.fontSize(10).fillColor("#666").text(label, { continued: true });
      doc.fillColor("#000").text(`  ${value}`);
    };

    row("Property", data.propertyName);
    row("Address", data.propertyAddress);
    row("Tenant", `${data.tenantName} (${data.tenantEmail})`);
    doc.moveDown(0.8);
    row("Due date", day(data.dueDate));
    row("Paid on", day(data.paymentDate));
    row("Status", data.paymentStatus);
    doc.moveDown(0.8);
    row("Amount due", money(data.amountDue));
    row("Amount paid", money(data.amountPaid));

    doc.moveDown(2);
    doc
      .fontSize(9)
      .fillColor("#888")
      .text(
        "Generated by Rentiful. This document is a record of payment and is not a tax invoice.",
        { align: "left" }
      );

    doc.end();
  });
